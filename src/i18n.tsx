const dictionaries: Record<Language, Record<string, string>> = { zh, en, ja };

const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => readStoredLanguage());

  useEffect(() => {
    window.localStorage.setItem(storageKey, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage: setLanguageState,
    t: (key, vars) => interpolate(
      cleanTranslations[language][key] ?? fleetViewTranslations[language][key] ?? dictionaries[language][key] ?? fallbackTranslations[language][key] ?? cleanTranslations.zh[key] ?? fleetViewTranslations.zh[key] ?? dictionaries.zh[key] ?? fallbackTranslations.zh[key] ?? key,
      vars,
    ),
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used inside LanguageProvider');
  }
  return context;
}

export function getLocale(language: Language) {
  return languageOptions.find((option) => option.id === language)?.locale ?? 'zh-CN';
}

function readStoredLanguage(): Language {
  if (typeof window === 'undefined') {
    return 'zh';
  }

  const stored = window.localStorage.getItem(storageKey);
  return stored === 'en' || stored === 'ja' || stored === 'zh' ? stored : 'zh';
}

function interpolate(template: string, vars?: TranslationVars) {
  if (!vars) {
    return template;
  }

  return Object.entries(vars).reduce(
    (current, [key, value]) => current.replaceAll(`{${key}}`, String(value)),
    template,
  );
}
